'use strict';
// Собирает D:/ShotMOD/README.md из build/catalog.json.
const fs = require('fs');
const path = require('path');
const config = require('./config.js');

const ROOT = path.resolve(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'build', 'catalog.json'), 'utf8'));
const KINDS = [
  ['levels', 'Паки уровней (без кода и без графики — используют врагов и боссов самой игры)'],
  ['pack', 'Паки врагов и боссов (новая графика, свои враги, босс и уровни — всё описано данными)'],
  ['script', 'Скриптовые моды (меняют правила игры; содержат код GDScript)'],
];
const kindName = { levels: 'уровни', pack: 'враги+босс+уровни', script: 'скрипт' };

const count = Object.keys(catalog).length;
const plural = (n) => (n % 10 === 1 && n % 100 !== 11 ? 'мод' : (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? 'мода' : 'модов'));
const lines = [];
lines.push('# Моды для ShootIn', '',
  `Готовые к публикации моды для игры **ShootIn** (${count} ${plural(count)}). Автор в \`mod.json\` каждого мода: **${config.author}** — поменяй перед публикацией (см. «Пересборка»).`, '',
  'В папке:', '',
  '| Папка | Что там |', '|---|---|',
  '| `dist/` | **готовые `.zip`-архивы — их и публикуй** (`<id>-1.0.0.zip`) |',
  '| `covers/` | обложки 630×500 для страниц публикации (`<id>.png`) |',
  '| `screenshots/` | кадры из игры для галереи |',
  '| `mods/` | исходные папки модов (то, что внутри архивов) |',
  '| `src/` | исходники скриптов для скриптовых модов |',
  '| `tools/` | сборка, проверка и упаковка (Node.js + Godot) |', '');

lines.push('## Список модов', '');
for (const [kind, title] of KINDS) {
  const items = Object.values(catalog).filter((m) => m.kind === kind).sort((a, b) => a.name.localeCompare(b.name, 'ru'));
  if (!items.length) continue;
  lines.push(`### ${title}`, '', '| Мод | Что делает | Уровней |', '|---|---|---|');
  for (const m of items) lines.push(`| **${m.name}** (\`${m.id}\`) | ${m.tagline} | ${m.levels || '—'} |`);
  lines.push('');
}

lines.push('> **Хардкор** 1.1.0 и **Спидран-таймер** 1.1.0 используют API модов 2 (настройки мода) и требуют игру **ShootIn 1.1.0** и новее; остальные моды работают и в версии 1.0.0.', '');

lines.push('## Как установить мод игроку', '',
  '1. Запусти ShootIn → **Моды** → **Установить из файла…** → выбери `.zip` (или вставь ссылку и нажми **Скачать и установить**).',
  '2. Поставь галочку у мода. Скриптовые моды покажут предупреждение — их код открытый, его можно прочитать (`scripts/main.gd` внутри архива).',
  '3. Паки уровней и паки врагов запускаются кнопкой **Играть**; скриптовые работают в любой игре (и в основной кампании, и в кампаниях других модов).',
  '', 'Архив распаковывать не нужно: игра читает `.zip` сама. Несколько модов можно включать одновременно — например «Хардкор» + «Берсерк» + «Полоски здоровья и урон».', '');

lines.push('## Идеи сочетаний', '',
  '- **Для новичков:** «Полигон» + «Полоски здоровья и урон» + «Яблоки с врагов».',
  '- **Для профи:** «Хардкор» + «Жажда крови» + «Спидран-таймер» (режим «Вся игра») + «Босс-раш».',
  '- **Без права на ошибку:** «Хардкор» (смерть — игра с 1 уровня; в настройках — убить всех врагов в финале, «ультра-хардкор»: любой урон убивает, «крепкие враги»).',
  '- **Для веселья:** «Режим хаоса» + «Лунная гравитация» + «Двойной прыжок» + «Небесные острова».',
  '- **Кино:** «Финальный удар» + «Босс-раш».', '');

lines.push('## Публикация', '',
  '1. Проверь автора и лицензию (ниже).',
  '2. Для каждого мода загрузи `dist/<id>-<версия>.zip`, обложку из `covers/` и описание из `mods/<id>/README.md` (там уже готовый текст на русском: что внутри, как установить).',
  '3. Добавь 1–3 кадра из `screenshots/`.',
  '4. Если что-то поменял — пересобери (раздел ниже) и перепакуй: версия берётся из `tools/config.js`.', '');

lines.push('## Лицензия и авторы графики', '',
  'Карты, скрипты и описания модов — авторские (лицензию выбирает публикующий). Графика паков врагов — **перекрашенные спрайты наборов LuizMelo (CC0)**: Monsters Creatures Fantasy, Monsters Creatures Fantasy 2, Medieval King Pack 2, Hero Knight, Evil Wizard 2 — https://luizmelo.itch.io/ . CC0 разрешает использование и изменение без обязательной атрибуции, но упомянуть автора приятно; это уже есть в README каждого мода. Паки уровней и скриптовые моды своей графики не содержат.', '');

lines.push('## Пересборка и проверка', '',
  'Нужны Node.js и Godot 4.3 (путь к нему — переменная `GODOT`, по умолчанию Desktop), игра лежит в `D:/shootin`.', '',
  '```',
  'node tools/build.js                   # собрать все моды (карты проверяет валидатор игры)',
  'node tools/build.js --author "Имя"     # то же, с другим автором в mod.json',
  'node tools/build.js trap_temple        # собрать один мод',
  'node tools/godot_isolated.js --headless --script D:/ShotMOD/tools/pack.gd          # упаковать в dist/*.zip',
  'node tools/godot_isolated.js --headless --script D:/ShotMOD/tools/check_dist.gd    # поставить архивы как игрок и загрузить все уровни',
  'node tools/godot_isolated.js --headless --script D:/ShotMOD/tools/test_script_mods.gd   # проверить поведение скриптовых модов',
  'node tools/godot_isolated.js --headless --script D:/ShotMOD/tools/test_hardcore.gd  # проверить «Хардкор»: настройки, смерть, ультра, крепкие враги, финал',
  'node tools/godot_isolated.js --headless --script D:/ShotMOD/tools/test_speedrun.gd  # проверить «Спидран-таймер»: вся игра, рекорд забега, разница, возобновление',
  'node tools/godot_isolated.js --resolution 1280x720 --script D:/ShotMOD/tools/make_hardcore_shots.gd   # кадры для публикации (нужно окно)',
  '```', '',
  'Проверки запускаются через `tools/godot_isolated.js`: он подменяет папку данных Godot (APPDATA), поэтому тесты не трогают твои настоящие сохранения, настройки и установленные моды. Запускать их напрямую через `godot --script …` не стоит.', '',
  'Скрипты скриптовых модов лежат в `src/<id>/scripts/main.gd` — правь их и пересобирай.', '');

fs.writeFileSync(path.join(ROOT, 'README.md'), lines.join('\n'));
console.log('README.md готов');
