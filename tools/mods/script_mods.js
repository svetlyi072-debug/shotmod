module.exports = function build() {
  return MODS.map((m) => {
    const mod = new Mod(m.id, {
      name: m.name, kind: 'script', tagline: m.tagline, features: m.features, notes: m.notes,
      about: ['Мод со скриптами: код — обычный текст в `scripts/main.gd` (его можно прочитать и поменять).'],
      credits: 'Код и описание — автор мода. Мод использует только API модов ShootIn (`extends ModScript`).',
    });
    mod.copy(path.join(ROOT, 'src', m.id, 'scripts', 'main.gd'), 'scripts/main.gd');
    mod.finish(Object.assign({ scripts: ['scripts/main.gd'] }, m.api ? { api: m.api } : {}, m.version ? { version: m.version } : {}, m.settings ? { settings: m.settings } : {}));
    return mod;
  });
};
